<?php

namespace ShmuelAKam\Greenjeans\Tests\Persistence\Data;

use ShmuelAKam\Greenjeans\Api\Data\API_Date;
use ShmuelAKam\Greenjeans\Persistence\Mappers\Data\DB_DateMapper;
use ShmuelAKam\Greenjeans\Tests\Persistence\DB_MapperTestBase;
use ShmuelAKam\Greenjeans\Tests\Persistence\Help\FactoryMapperDates;

/**
 * DB_DateMapperTest
 * Unit tests for DB_DateMapper database persistence layer.
 */
class DB_DateMapperTest extends DB_MapperTestBase
{
    private DB_DateMapper $mapper;

    protected function setUp(): void
    {
        parent::setUp();

        $this->mapper = $this->persistor->getMapper(DB_DateMapper::class);
    }

    // =====================================================
    // Test Data Providers

    /**
     * @return array <string, array <string>>
     */
    public static function provideDatePresets(): array
    {
        $data = [];

        foreach (array_keys(FactoryMapperDates::DATE_PRESETS) as $key)
        {
            $data[$key] = [$key];
        }

        return $data;
    }

    // =====================================================
    // Custom Assert Helpers

    /**
     * Compare parameter arrays generated by API_Date objects.
     */
    protected function assertEqualsDate(API_Date $expected, API_Date $actual, string $message = ''): void
    {
        $expParams = $expected->makeParamArray();
        $actParams = $actual->makeParamArray();

        self::assertEquals($expParams['year'] ?? null, $actParams['year'] ?? null, $message . ' [year mismatch]');
        self::assertEquals($expParams['month'] ?? null, $actParams['month'] ?? null, $message . ' [month mismatch]');
        self::assertEquals($expParams['day'] ?? null, $actParams['day'] ?? null, $message . ' [day mismatch]');

        if (!empty($expParams['circa']))
        {
            self::assertTrue((bool) ($actParams['circa'] ?? false), $message . ' [circa mismatch]');
        }

        if (isset($expParams['range']))
        {
            self::assertEquals($expParams['range'], $actParams['range'] ?? null, $message . ' [range mismatch]');
            self::assertEquals($expParams['end_year'] ?? null, $actParams['end_year'] ?? null, $message . ' [end_year mismatch]');
        }
    }

    // =====================================================
    // Basic Persistence Tests

    /**
     * Verifies persistence and retrieval across all date presets.
     * @dataProvider provideDatePresets
     */
    public function testCreateAndReadDatePresets(string $presetKey): void
    {
        /** @var FactoryMapperDates $dateMapFactory */
        global $dateMapFactory;

        $ownerID = 'event-test-owner-001';
        $dateObj = $dateMapFactory->makePresetDate($presetKey);

        //-------------------------------
        $insertedID = $this->mapper->save($dateObj, $ownerID);

        $retrieved = $this->mapper->read($insertedID);
        //-------------------------------

        $this->assertGreaterThan(0, $insertedID);
        $this->assertNotNull($retrieved);
        $this->assertEqualsDate($dateObj, $retrieved);
    }

    /**
     * Verifies array cleaning filters out zeroed/falsy circa flags and null values.
     */
    public function testReadArrayFiltersUnsetAndFalseCirca(): void
    {
        /** @var FactoryMapperDates $dateMapFactory */
        global $dateMapFactory;

        $ownerID   = 'event-test-owner-003';
        $exactDate = $dateMapFactory->makePresetDate('exact_date'); // circa = false

        $insertedID = $this->mapper->save($exactDate, $ownerID);

        //-------------------------------
        $rawArray = $this->mapper->readArray($insertedID);
        //-------------------------------

        $this->assertIsArray($rawArray);
        // Null columns must be filtered out
        $this->assertArrayNotHasKey('end_year', $rawArray);
        // False/0 circa flags must be omitted entirely
        $this->assertArrayNotHasKey('circa', $rawArray);
        $this->assertArrayNotHasKey('end_circa', $rawArray);
    }

    /**
     * Verifies date_range column renaming back to range.
     */
    public function testReadArrayRemapsDateRangeColumn(): void
    {
        /** @var FactoryMapperDates $dateMapFactory */
        global $dateMapFactory;

        $ownerID   = 'event-test-owner-004';
        $rangeDate = $dateMapFactory->makePresetDate('date_range');

        $insertedID = $this->mapper->save($rangeDate, $ownerID);

        $rawArray = $this->mapper->readArray($insertedID);

        $this->assertIsArray($rawArray);
        $this->assertArrayHasKey('range', $rawArray);
        $this->assertArrayNotHasKey('date_range', $rawArray);
        $this->assertEquals('between', $rawArray['range']);
    }

    /**
     * Verifies reading non-existent date integer ID returns null.
     */
    public function testReadNonExistentReturnsNull(): void
    {
        $this->assertNull($this->mapper->readArray(999999));
    }

    /**
     * Verifies deleting a date record.
     */
    public function testDeleteDate(): void
    {
        /** @var FactoryMapperDates $dateMapFactory */
        global $dateMapFactory;

        $ownerID = 'event-test-owner-005';
        $dateObj = $dateMapFactory->makePresetDate('exact_date');

        $insertedID = $this->mapper->save($dateObj, $ownerID);
        $this->assertNotNull($this->mapper->read($insertedID));

        //-------------------------------
        $this->mapper->delete($insertedID);
        //-------------------------------

        $this->assertNull($this->mapper->readArray($insertedID));
    }
}
