<?php

namespace ShmuelAKam\Greenjeans\Tests\Persistence\Data;

use ShmuelAKam\Greenjeans\Api\Data\API_Name;
use ShmuelAKam\Greenjeans\Persistence\Mappers\Data\DB_NameMapper;
use ShmuelAKam\Greenjeans\Tests\Persistence\DB_MapperTestBase;
use ShmuelAKam\Greenjeans\Tests\Persistence\Help\FactoryMapperNames;

/**
 * DB_NameMapperTest
 * Unit tests for DB_NameMapper database persistence layer.
 */
class DB_NameMapperTest extends DB_MapperTestBase
{
    private DB_NameMapper $mapper;

    protected function setUp(): void
    {
        parent::setUp();

        $this->mapper = $this->persistor->getMapper(DB_NameMapper::class);
    }

    // =====================================================
    // Test Data Providers

    /**
     * @return array <string, array <string>>
     */
    public static function provideNamePresets(): array
    {
        $data = [];

        foreach (array_keys(FactoryMapperNames::NAME_PRESETS) as $key)
        {
            $data [$key] = [ $key ];
        }

        return $data;
    }

    // =====================================================
    // Custom Assert Helpers

    /**
     * Compare parameter arrays generated by API_Name objects.
     */
    protected function assertEqualsName(API_Name $expected, API_Name $actual, string $message = ''): void
    {
        $expParams = $expected->makeParamArray();
        $actParams = $actual->makeParamArray();

        self::assertEquals($expParams['display_name'] ?? null, $actParams['display_name'] ?? null, $message . ' [display_name mismatch]');
        self::assertEquals($expParams['first_name'] ?? null, $actParams['first_name'] ?? null, $message . ' [first_name mismatch]');
        self::assertEquals($expParams['last_name'] ?? null, $actParams['last_name'] ?? null, $message . ' [last_name mismatch]');
        self::assertEquals($expParams['maiden_name'] ?? null, $actParams['maiden_name'] ?? null, $message . ' [maiden_name mismatch]');
        self::assertEquals($expParams['middle_name'] ?? null, $actParams['middle_name'] ?? null, $message . ' [middle_name mismatch]');
        self::assertEquals($expParams['suffix'] ?? null, $actParams['suffix'] ?? null, $message . ' [suffix mismatch]');
        self::assertEquals($expParams['title'] ?? null, $actParams['title'] ?? null, $message . ' [title mismatch]');

        self::assertEquals($expected->getNicknames(), $actual->getNicknames(), $message . ' [nicknames mismatch]');
    }

    // =====================================================
    // Basic Persistence Tests

    /**
     * Verifies persistence and retrieval of single locale localized names.
     * @dataProvider provideNamePresets
     */
    public function testCreateAndReadNamePresets(string $presetKey): void
    {
        /** @var FactoryMapperNames $nameMapFactory */
        global $nameMapFactory;

        $profileID = 'profile-test-name-001';
        $locale    = 'en-US';
        $name      = $nameMapFactory->makePresetName($presetKey);

        //-------------------------------
        $insertedID = $this->mapper->create($name, $profileID, $locale);

        $retrievedAll = $this->mapper->readAll($profileID);
        //-------------------------------

        $this->assertGreaterThan(0, $insertedID);
        $this->assertArrayHasKey($locale, $retrievedAll);
        $this->assertEqualsName($name, $retrievedAll[$locale]);
    }

    /**
     * Verifies saving multiple localized names across different locales for a single profile.
     */
    public function testCreateAllAndReadAllMultipleLocales(): void
    {
        /** @var FactoryMapperNames $nameMapFactory */
        global $nameMapFactory;

        $profileID = 'profile-test-name-002';

        $names = [
            'en-US' => $nameMapFactory->makePresetName('full_name'),
            'fr-FR' => $nameMapFactory->makePresetName('maiden_name'),
            'de-DE' => $nameMapFactory->makePresetName('simple_name'),
        ];

        //-------------------------------
        $this->mapper->createAll($names, $profileID);

        $retrieved = $this->mapper->readAll($profileID);
        //-------------------------------

        $this->assertCount(3, $retrieved);
        $this->assertArrayHasKey('en-US', $retrieved);
        $this->assertArrayHasKey('fr-FR', $retrieved);
        $this->assertArrayHasKey('de-DE', $retrieved);

        $this->assertEqualsName($names['en-US'], $retrieved['en-US']);
        $this->assertEqualsName($names['fr-FR'], $retrieved['fr-FR']);
        $this->assertEqualsName($names['de-DE'], $retrieved['de-DE']);
    }

    /**
     * Verifies reading names for a profile with no records returns an empty array.
     */
    public function testReadAllEmptyReturnsEmptyArray(): void
    {
        $retrieved = $this->mapper->readAll('profile-non-existent-999');

        $this->assertEmpty($retrieved);
    }

    /**
     * Verifies deleting all localized names for a profile.
     */
    public function testDeleteAll(): void
    {
        /** @var FactoryMapperNames $nameMapFactory */
        global $nameMapFactory;

        $profileID = 'profile-test-name-003';

        $names = [
            'en-US' => $nameMapFactory->makePresetName('full_name'),
            'en-GB' => $nameMapFactory->makePresetName('simple_name'),
        ];

        $this->mapper->createAll($names, $profileID);
        $this->assertCount(2, $this->mapper->readAll($profileID));

        //-------------------------------
        $this->mapper->deleteAll($profileID);
        //-------------------------------

        $this->assertCount(0, $this->mapper->readAll($profileID));
    }
}
