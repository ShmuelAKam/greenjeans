<?php

namespace ShmuelAKam\Greenjeans\Tests\Persistence\Data;

use ShmuelAKam\Greenjeans\Api\Data\API_PhoneNumber;
use ShmuelAKam\Greenjeans\Persistence\Mappers\Data\DB_PhoneNumberMapper;
use ShmuelAKam\Greenjeans\Tests\Persistence\DB_MapperTestBase;
use ShmuelAKam\Greenjeans\Tests\Persistence\Help\FactoryMapperBase;
use ShmuelAKam\Greenjeans\Tests\Persistence\Help\FactoryMapperPhoneNumbers;

/**
 * DB_PhoneNumberMapperTest
 * Unit tests for DB_PhoneNumberMapper database persistence layer.
 */
class DB_PhoneNumberMapperTest extends DB_MapperTestBase
{
    private DB_PhoneNumberMapper $mapper;

    protected function setUp(): void
    {
        parent::setUp();

        $this->mapper = $this->getMapper(DB_PhoneNumberMapper::class);
    }

    // =====================================================
    // Test Data Providers

    /**
     * @return array <string, array <string>>
     */
    public static function providePhonePresets(): array
    {
        $data = [];

        foreach (array_keys(FactoryMapperPhoneNumbers::PHONE_PRESETS) as $key)
        {
            $data[$key] = [$key];
        }

        return $data;
    }

    // =====================================================
    // Custom Assert Helpers

    /**
     * Compare parameters generated by API_PhoneNumber objects.
     */
    protected function assertEqualsPhoneNumber(API_PhoneNumber $expected, API_PhoneNumber $actual, string$message = ''): void
    {
        self::assertEquals($expected->getAreaCode(), $actual->getAreaCode(), $message . ' [area_code mismatch]');
        self::assertEquals($expected->getCountryCode(), $actual->getCountryCode(), $message . ' [country_code mismatch]');
        self::assertEquals($expected->getNumber(), $actual->getNumber(), $message . ' [number mismatch]');
        self::assertEquals($expected->getType(), $actual->getType(), $message . ' [type mismatch]');
    }

    // =====================================================
    // Basic Persistence Tests

    /**
     * Verifies creation and reading of single phone numbers across all presets.
     * @dataProvider providePhonePresets
     */
    public function testCreateAndReadPhonePresets(string $presetKey): void
    {
        /** @var FactoryMapperPhoneNumbers $phoneMapFactory */
        $phoneMapFactory = FactoryMapperBase::getFactory(API_PhoneNumber::class);

        $ownerID     = 'profile-test-owner-201';
        $phoneNumber = $phoneMapFactory->makePresetPhoneNumber($presetKey);

        //-------------------------------
        $insertedID = $this->mapper->save($phoneNumber, $ownerID);

        $retrieved = $this->mapper->read($insertedID);
        //-------------------------------

        $this->assertGreaterThan(0, $insertedID);
        $this->assertNotNull($retrieved);
        $this->assertEqualsPhoneNumber($phoneNumber, $retrieved);
    }

    /**
     * Verifies reading non-existent phone number integer ID returns empty payload or null-equivalent.
     */
    public function testReadNonExistentReturnsEmptyPhoneObject(): void
    {
        $retrieved = $this->mapper->read(999999);

        $this->assertNull($retrieved);
    }

    // =====================================================
    // Batch Collection Tests (`createAll` / `readAll` / `deleteAll`)

    /**
     * Verifies createAll persists multiple numbers for an owner entity.
     */
    public function testCreateAllAndReadAllForOwner(): void
    {
        /** @var FactoryMapperPhoneNumbers $phoneMapFactory */
        $phoneMapFactory = FactoryMapperBase::getFactory(API_PhoneNumber::class);

        $ownerID = 'profile-test-owner-202';

        $phoneNumbers = [$phoneMapFactory->makePresetPhoneNumber('mobile_us'),
            $phoneMapFactory->makePresetPhoneNumber('work_uk'),$phoneMapFactory->makePresetPhoneNumber('fax'),
        ];

        //-------------------------------
        $this->mapper->createAll($phoneNumbers, $ownerID);

        $retrievedNumbers = $this->mapper->readAll($ownerID);
        //-------------------------------

        $this->assertCount(3, $retrievedNumbers);
        $this->assertEqualsPhoneNumber($phoneNumbers[0], $retrievedNumbers[0]);
        $this->assertEqualsPhoneNumber($phoneNumbers[1], $retrievedNumbers[1]);
        $this->assertEqualsPhoneNumber($phoneNumbers[2], $retrievedNumbers[2]);
    }

    /**
     * Verifies that createAll automatically clears existing phone numbers for the owner before persisting.
     */
    public function testCreateAllClearsExistingNumbers(): void
    {
        /** @var FactoryMapperPhoneNumbers $phoneMapFactory */
        $phoneMapFactory = FactoryMapperBase::getFactory(API_PhoneNumber::class);

        $ownerID = 'profile-test-owner-203';

        $initialNumbers = [
            $phoneMapFactory->makePresetPhoneNumber('home_us'),$phoneMapFactory->makePresetPhoneNumber('work_uk'),
        ];

        $this->mapper->createAll($initialNumbers, $ownerID);
        $this->assertCount(2, $this->mapper->readAll($ownerID));

        // Overwrite with a single new mobile number
        $newNumbers = [$phoneMapFactory->makePresetPhoneNumber('mobile_us'),
        ];

        //-------------------------------
        $this->mapper->createAll($newNumbers, $ownerID);
        //-------------------------------

        $retrieved = $this->mapper->readAll($ownerID);

        $this->assertCount(1, $retrieved);
        $this->assertEquals('mobile', $retrieved[0]->getType());
        $this->assertEquals('5550143', $retrieved[0]->getNumber());
    }

    /**
     * Verifies single and bulk deletion of phone numbers.
     */
    public function testDeleteAndDeleteAll(): void
    {
        /** @var FactoryMapperPhoneNumbers $phoneMapFactory */
        $phoneMapFactory = FactoryMapperBase::getFactory(API_PhoneNumber::class);

        $ownerID     = 'profile-test-owner-204';
        $phoneNumber = $phoneMapFactory->makePresetPhoneNumber('mobile_us');

        $insertedID = $this->mapper->save($phoneNumber, $ownerID);
        $this->assertCount(1, $this->mapper->readAll($ownerID));

        //-------------------------------
        // Delete single phone number
        $this->mapper->delete($insertedID);
        $this->assertCount(0, $this->mapper->readAll($ownerID));
        //-------------------------------

        // Bulk delete via deleteAll
        $this->mapper->createAll([$phoneNumber,$phoneNumber], $ownerID);
        $this->assertCount(2, $this->mapper->readAll($ownerID));

        //-------------------------------
        $this->mapper->deleteAll($ownerID);
        $this->assertCount(0, $this->mapper->readAll($ownerID));
        //-------------------------------
    }
}
